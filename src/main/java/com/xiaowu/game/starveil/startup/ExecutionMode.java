package com.xiaowu.game.starveil.startup;

/**
 * 启动参数处理器的执行模式
 */
public enum ExecutionMode {
    /**
     * 并行模式：处理器代码与Launcher主代码同时执行，不阻塞游戏启动
     * 适用于：配置设置、日志级别设置等不影响游戏启动的功能
     */
    PARALLEL,

    /**
     * 重写模式：拦截Launcher，不执行游戏主代码，只执行处理器的代码
     * 适用于：工具命令、特殊模式等需要完全替代游戏启动的功能
     */
    OVERRIDE,

    /**
     * 阻塞模式：在执行游戏主代码之前先执行处理器的代码，等待完成后才继续执行游戏主代码
     * 适用于：前置资源加载、初始化必要的配置、启动前的检查等需要在游戏启动前完成的功能
     */
    BLOCKING
}